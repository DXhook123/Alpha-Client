inline bool& getChineseMode() {
    static bool sChinese = false;
    return sChinese;
}
inline void setChineseMode(bool on) { getChineseMode() = on; }

inline std::string queryModuleName(const std::string& modName) {
    if (!getChineseMode()) return modName;
    auto it = ModuleChineseNames.find(modName);
    return it != ModuleChineseNames.end() ? it->second : modName;
}

inline std::string queryModuleDescription(const std::string& modName, const std::string& fallbackDesc) {
    if (!getChineseMode()) return fallbackDesc;
    auto it = ModuleChineseDescriptions.find(modName);
    return (it != ModuleChineseDescriptions.end() && !it->second.empty()) ? it->second : fallbackDesc;
}

inline std::string queryCategoryName(int catIndex, const std::string& fallbackName) {
    if (!getChineseMode()) return fallbackName;
    if (catIndex >= 0 && catIndex < (int)ModuleCategoryChineseNames.size())
        return ModuleCategoryChineseNames[catIndex];
    return fallbackName;
}

inline std::string queryEnumValueTranslation(const std::string& enumValue) {
    if (!getChineseMode()) return enumValue;
    auto it = EnumValueChinese.find(enumValue);
    if (it != EnumValueChinese.end()) return it->second;
    return enumValue;
}

inline std::string simplifySettingDisplayName(const std::string& displayName) {
    static const std::string prefix = "LiquidBounce ";
    if (displayName.rfind(prefix, 0) == 0)
        return displayName.substr(prefix.size());
    return displayName;
}

inline std::pair<std::string, std::string> querySettingTranslation(
    const std::string& modName,
    const std::string& settingName,
    const std::string& fallbackName,
    const std::string& fallbackDesc)
{
    if (!getChineseMode()) return {simplifySettingDisplayName(fallbackName), fallbackDesc};

    std::string displayName;
    std::string description;

    auto modIt = SettingChineseOverrides.find(modName + "::" + settingName);
    if (modIt != SettingChineseOverrides.end()) {
        if (!modIt->second.first.empty())  displayName = modIt->second.first;
        if (!modIt->second.second.empty()) description = modIt->second.second;
    }
    if (modName == "AlphaAutoCrystal" && (displayName.empty() || description.empty())) {
        auto sourceIt = SettingChineseOverrides.find("AutoCrystal::" + settingName);
        if (sourceIt != SettingChineseOverrides.end()) {
            if (displayName.empty() && !sourceIt->second.first.empty()) displayName = sourceIt->second.first;
            if (description.empty() && !sourceIt->second.second.empty()) description = sourceIt->second.second;
        }
    }
    auto commonIt = CommonSettingChinese.find(settingName);
    if (commonIt != CommonSettingChinese.end()) {
        if (displayName.empty()  && !commonIt->second.first.empty())  displayName  = commonIt->second.first;
        if (description.empty() && !commonIt->second.second.empty()) description = commonIt->second.second;
    }

    if (displayName.empty())  displayName  = fallbackName;
    if (description.empty()) description = fallbackDesc;

    return {simplifySettingDisplayName(displayName), description};
}
inline std::vector<uint32_t> collectTranslationCodepoints() {
    std::set<uint32_t> chars;

    auto collect = [&](const std::string& s) {
        size_t i = 0;
        while (i < s.size()) {
            unsigned char c = static_cast<unsigned char>(s[i]);
            if (c < 0x80) { i++; continue; }
            uint32_t wc = 0;
            int len = 0;
            if ((c & 0xE0) == 0xC0) { wc = c & 0x1F; len = 2; }
            else if ((c & 0xF0) == 0xE0) { wc = c & 0x0F; len = 3; }
            else if ((c & 0xF8) == 0xF0) { wc = c & 0x07; len = 4; }
            else { i++; continue; }
            for (int j = 1; j < len && i + j < s.size(); j++) {
                wc = (wc << 6) | (static_cast<unsigned char>(s[i + j]) & 0x3F);
            }
            if (wc >= 0x4E00) chars.insert(wc);
            i += len;
        }
    };

    for (auto& [k, v] : ModuleChineseNames)         { collect(k); collect(v); }
    for (auto& [k, v] : ModuleChineseDescriptions)  { collect(k); collect(v); }
    for (auto& s : ModuleCategoryChineseNames)      { collect(s); }
    for (auto& [k, v] : CommonSettingChinese)       { collect(k); collect(v.first); collect(v.second); }
    for (auto& [k, v] : SettingChineseOverrides)    { collect(k); collect(v.first); collect(v.second); }
    for (auto& [k, v] : EnumValueChinese)           { collect(k); collect(v); }
    static const std::vector<std::string> sFixedUiStrings = {
        "按下新按键...", "NONE", "搜索", "设置", "模块", "描述",
        "折叠符展开符两遍绘制展开坑",
        "潜影盒白色橙品红淡蓝黄绿粉灰青紫棕黑",
    };
    for (auto& s : sFixedUiStrings) { collect(s); }

    return std::vector<uint32_t>(chars.begin(), chars.end());
}

inline const uint16_t* getTranslationGlyphRanges() {
    static std::vector<uint16_t> sRanges;
    static bool sBuilt = false;
    if (sBuilt) return sRanges.data();

    auto chars = collectTranslationCodepoints();
    std::sort(chars.begin(), chars.end());
    chars.erase(std::unique(chars.begin(), chars.end()), chars.end());

	sRanges.push_back(0x3000);
	sRanges.push_back(0x30FF);
	sRanges.push_back(0x31F0);
	sRanges.push_back(0x31FF);
	sRanges.push_back(0x4E00);
	sRanges.push_back(0x9FA5);
	sRanges.push_back(0xFF00);
	sRanges.push_back(0xFFEF);

    for (size_t i = 0; i < chars.size();) {
		if (chars[i] <= 0x9FA5) {
			++i;
			continue;
		}
        uint16_t start = static_cast<uint16_t>(chars[i]);
        uint16_t end = start;
        i++;
        while (i < chars.size() && chars[i] == static_cast<uint32_t>(end) + 1) {
            end = static_cast<uint16_t>(chars[i]);
            i++;
        }
        sRanges.push_back(start);
        sRanges.push_back(end);
    }

    sRanges.push_back(0);
    sRanges.push_back(0);

    sBuilt = true;
    return sRanges.data();
}
