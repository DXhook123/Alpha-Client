inline int nativeActorFlagIndex(ActorFlags flag) {
	const int index = static_cast<int>(flag);
	if (!SdkVersion::is12651()) return index;
	if (flag == ActorFlags::Wasd || flag == ActorFlags::TouchControlled) return -1;
	return index >= static_cast<int>(ActorFlags::Lingering) ? index - 2 : index;
}
